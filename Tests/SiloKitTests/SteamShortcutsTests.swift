import Foundation
import Testing
@testable import SiloKit

struct SteamShortcutsTests {
    /// What macOS Steam wrote for TEKKEN 8 (2026-11-18).
    static let steamScript = "#!/bin/bash\n# autogenerated file - do not edit\n\nopen steam://run/1778820\n"

    @Test("The game of a Steam shortcut script; nothing for another script")
    func appID() {
        #expect(SteamShortcuts.appID(runScript: Self.steamScript) == 1778820)
        let ours = SteamShortcuts.runScript(appID: 1778820, steamLauncher: URL(fileURLWithPath: "/H/Applications/Steam (Silo).app"))
        #expect(SteamShortcuts.appID(runScript: ours) == 1778820)   // our rewrite keeps Steam's line
        #expect(SteamShortcuts.appID(runScript: "#!/bin/sh\nopen -a Safari\n") == nil)
        #expect(SteamShortcuts.appID(runScript: "open steam://run/abc\n") == nil)
    }

    @Test("Silo's script quotes the launcher path and opens it only when Steam isn't running")
    func script() {
        let script = SteamShortcuts.runScript(appID: 7, steamLauncher: URL(fileURLWithPath: "/H/it's/Steam (Silo).app"))
        #expect(script.contains("L='/H/it'\\''s/Steam (Silo).app'"))
        #expect(script.contains("if ! /usr/bin/pgrep -x steam_osx"))
        #expect(script.hasSuffix("fi\nopen steam://run/7\n"))
    }

    @Test("Steam's shortcuts of Silo's Windows games get the game icon and Steam (Silo); the rest is left alone")
    func fix() throws {
        let tmp = try TempDir(); defer { tmp.cleanup() }
        let home = tmp.url.appendingPathComponent("home")
        let gameApps = tmp.url.appendingPathComponent("GameApps")
        let launcher = home.appendingPathComponent("Applications/Steam (Silo).app")
        _ = try tmp.write("home/Desktop/TEKKEN 8.app/Contents/MacOS/run.sh", Self.steamScript)
        _ = try tmp.write("home/Desktop/TEKKEN 8.app/Contents/Resources/shortcut.icns", "steam icon")
        _ = try tmp.write("home/Applications/Tomb Raider.app/Contents/MacOS/run.sh",
                          "#!/bin/bash\n# autogenerated file - do not edit\nopen steam://run/203160\n")   // a Mac game
        _ = try tmp.write("home/Desktop/Mine.app/Contents/MacOS/run.sh", "#!/bin/bash\nopen steam://run/1778820\n")
        _ = try tmp.write("GameApps/1778820/TEKKEN 8.app/Contents/Resources/AppIcon.icns", "tekken icon")

        let lines = SteamShortcuts.fix(home: home, gameAppsDir: gameApps, steamLauncher: launcher, games: [1778820])
        #expect(lines == ["shortcut Desktop/TEKKEN 8.app: starts Steam (Silo), game icon"])
        let tekken = home.appendingPathComponent("Desktop/TEKKEN 8.app/Contents")
        #expect(try String(contentsOf: tekken.appendingPathComponent("MacOS/run.sh"), encoding: .utf8)
                == SteamShortcuts.runScript(appID: 1778820, steamLauncher: launcher))
        #expect(try String(contentsOf: tekken.appendingPathComponent("Resources/shortcut.icns"), encoding: .utf8) == "tekken icon")
        let mode = try FileManager.default.attributesOfItem(atPath: tekken.appendingPathComponent("MacOS/run.sh").path)[.posixPermissions] as? Int
        #expect(mode == 0o755)
        #expect(try String(contentsOf: home.appendingPathComponent("Applications/Tomb Raider.app/Contents/MacOS/run.sh"),
                           encoding: .utf8).contains("open steam://run/203160"))   // not one of Silo's games
        #expect(try String(contentsOf: home.appendingPathComponent("Desktop/Mine.app/Contents/MacOS/run.sh"),
                           encoding: .utf8) == "#!/bin/bash\nopen steam://run/1778820\n")   // not Steam's
        // Idempotent.
        #expect(SteamShortcuts.fix(home: home, gameAppsDir: gameApps, steamLauncher: launcher, games: [1778820]).isEmpty)
    }
}
