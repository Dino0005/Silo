// Silo's in-Steam hook, Steam's shortcuts of the Windows games (SteamShortcuts.swift does the same at a game's launch).
// Steam writes a game's shortcut — ~/Desktop or ~/Applications, `<Game>.app` with `run.sh` = `open steam://run/<id>` —
// with its generic icon for a game that has no Mac icon, and the link opens Valve's Steam.app when Steam is closed. For a
// game Silo starts (it has a game app in Silo/GameApps), the shortcut gets the game's icon and a run.sh that opens
// "Steam (Silo)" first. Done here, inside Steam, because the Desktop is a protected folder: Steam may read it (it writes
// the shortcuts there), a Silo process would make macOS ask (measured 2026-11-18: the guard did). Every 5 s, not while a
// game started through Silo runs. The script MUST stay byte-for-byte SteamShortcuts.runScript's, or the two would keep
// rewriting each other.
#import <AppKit/AppKit.h>

void silo_hook_log(const char *fmt, ...);

static NSString *silo_run_script(int appID, NSString *launcher) {
    NSString *quoted = [NSString stringWithFormat:@"'%@'", [launcher stringByReplacingOccurrencesOfString:@"'"
                                                                                               withString:@"'\\''"]];
    return [NSString stringWithFormat:
        @"#!/bin/bash\n"
         "# autogenerated file - do not edit\n"
         "# Silo: opens \"Steam (Silo)\" first when Steam isn't running\n"
         "L=%@\n"
         "if ! /usr/bin/pgrep -x steam_osx >/dev/null && [ -d \"$L\" ]; then\n"
         "  /usr/bin/open \"$L\"\n"
         "  for i in $(seq 120); do /usr/bin/pgrep -x steam_osx >/dev/null && break; sleep 1; done\n"
         "  sleep 3\n"
         "fi\n"
         "open steam://run/%d\n", quoted, appID];
}

// The game of Steam's script: its `open steam://run/<id>` line; 0 for anything else.
static int silo_shortcut_app_id(NSString *text) {
    for (NSString *line in [text componentsSeparatedByCharactersInSet:NSCharacterSet.newlineCharacterSet]) {
        NSArray<NSString *> *words = [line componentsSeparatedByString:@" "];
        if (words.count == 2 && [words[0] isEqual:@"open"] && [words[1] hasPrefix:@"steam://run/"])
            return [[words[1] substringFromIndex:@"steam://run/".length] intValue];
    }
    return 0;
}

static NSString *silo_game_icon(NSString *gameApps, int appID) {
    NSString *dir = [gameApps stringByAppendingPathComponent:[NSString stringWithFormat:@"%d", appID]];
    for (NSString *entry in [NSFileManager.defaultManager contentsOfDirectoryAtPath:dir error:nil]) {
        if (![entry hasSuffix:@".app"]) continue;
        NSString *icon = [dir stringByAppendingPathComponent:[entry stringByAppendingPathComponent:@"Contents/Resources/AppIcon.icns"]];
        if ([NSFileManager.defaultManager fileExistsAtPath:icon]) return icon;
    }
    return nil;
}

static BOOL silo_game_running(void) {
    for (NSRunningApplication *app in NSWorkspace.sharedWorkspace.runningApplications) {
        NSString *bundle = app.bundleIdentifier;
        if ([bundle hasPrefix:@"io.github.dino0005.silo.game."] || [bundle hasPrefix:@"io.github.dino0005.silo.host."]) return YES;
    }
    return NO;
}

static void silo_fix_shortcuts(void) {
    NSString *home = NSHomeDirectory();
    NSString *gameApps = [home stringByAppendingPathComponent:@"Library/Application Support/Silo/GameApps"];
    NSString *launcher = [home stringByAppendingPathComponent:@"Applications/Steam (Silo).app"];
    NSFileManager *fm = NSFileManager.defaultManager;
    for (NSString *folder in @[@"Desktop", @"Applications"]) {
        NSString *dir = [home stringByAppendingPathComponent:folder];
        for (NSString *entry in [fm contentsOfDirectoryAtPath:dir error:nil]) {
            if (![entry hasSuffix:@".app"]) continue;
            NSString *app = [dir stringByAppendingPathComponent:entry];
            NSString *script = [app stringByAppendingPathComponent:@"Contents/MacOS/run.sh"];
            NSString *text = [NSString stringWithContentsOfFile:script encoding:NSUTF8StringEncoding error:nil];
            if (!text || ![text containsString:@"# autogenerated file"]) continue;
            int appID = silo_shortcut_app_id(text);
            NSString *icon = appID > 0 ? silo_game_icon(gameApps, appID) : nil;
            if (!icon) continue;   // not a game Silo starts (or never started yet)
            BOOL changed = NO;
            NSString *wanted = silo_run_script(appID, launcher);
            if (![text isEqualToString:wanted] && [wanted writeToFile:script atomically:YES encoding:NSUTF8StringEncoding error:nil]) {
                [fm setAttributes:@{NSFilePosixPermissions: @0755} ofItemAtPath:script error:nil];
                changed = YES;
            }
            NSString *shortcutIcon = [app stringByAppendingPathComponent:@"Contents/Resources/shortcut.icns"];
            NSData *data = [NSData dataWithContentsOfFile:icon];
            // In place, not swapped: no blank tile in the Finder between Steam's icon and the game's.
            if (data && ![[NSData dataWithContentsOfFile:shortcutIcon] isEqualToData:data] &&
                [data writeToFile:shortcutIcon atomically:NO]) changed = YES;
            if (changed) {
                [fm setAttributes:@{NSFileModificationDate: [NSDate date]} ofItemAtPath:app error:nil];
                silo_hook_log("shortcut %s/%s: game %d, icon and Steam (Silo)", folder.UTF8String, entry.UTF8String, appID);
            }
        }
    }
}

void silo_shortcuts_install(void) {
    dispatch_async(dispatch_get_main_queue(), ^{
        [NSTimer scheduledTimerWithTimeInterval:5 repeats:YES block:^(NSTimer *timer) {
            (void)timer;
            if (!silo_game_running()) silo_fix_shortcuts();
        }];
    });
}
