import Foundation

/// The shortcuts macOS Steam makes for a game (Manage → Add desktop shortcut, or the install dialog's Desktop /
/// Applications boxes): a tiny `.app` whose `run.sh` is `open steam://run/<id>`, with Steam's generic icon for a game
/// that has no Mac icon — every Windows game (measured 2026-11-18 on TEKKEN 8). Opened with Steam closed, the link
/// starts Valve's `Steam.app`, without Silo's library and grants.
///
/// For the Windows games that start through Silo, Silo rewrites them: the game's own icon (the one its game app shows in
/// the Dock), and a `run.sh` that opens "Steam (Silo)" first when Steam isn't running — the same hand-off as a start
/// from the Games app (`GameAppLoader.gamesHandoffEnvironment`). Idempotent; anything that isn't Steam's (or our
/// rewrite of Steam's) shortcut is left alone.
public enum SteamShortcuts {
    /// The line that tells our rewrite apart; the `open steam://run/<id>` line stays as Steam wrote it.
    static let marker = "# Silo: opens \"Steam (Silo)\" first when Steam isn't running"
    static let scriptName = "run.sh"
    static let iconName = "shortcut.icns"

    /// Pure: the game of a Steam shortcut script, from its `open steam://run/<id>` line; nil for anything else.
    static func appID(runScript text: String) -> Int? {
        for line in text.split(whereSeparator: \.isNewline) {
            let words = line.split(separator: " ")
            guard words.count == 2, words[0] == "open", words[1].hasPrefix("steam://run/") else { continue }
            return Int(words[1].dropFirst("steam://run/".count))
        }
        return nil
    }

    /// Pure: the `run.sh` Silo writes for `appID`.
    static func runScript(appID: Int, steamLauncher: URL) -> String {
        let launcher = "'" + steamLauncher.path.replacingOccurrences(of: "'", with: "'\\''") + "'"
        return """
        #!/bin/bash
        # autogenerated file - do not edit
        \(marker)
        L=\(launcher)
        if ! /usr/bin/pgrep -x steam_osx >/dev/null && [ -d "$L" ]; then
          /usr/bin/open "$L"
          for i in $(seq 120); do /usr/bin/pgrep -x steam_osx >/dev/null && break; sleep 1; done
          sleep 3
        fi
        open steam://run/\(appID)

        """
    }

    /// Rewrites the Steam shortcuts in `~/Desktop` and `~/Applications` of the games in `games` (the Windows games that
    /// start through Silo). The icon comes from the game's app in `gameAppsDir`, when Silo has made one (its first
    /// start from Steam). Returns one line per change, for the log.
    public static func fix(home: URL, gameAppsDir: URL, steamLauncher: URL, games: Set<Int>,
                           fileManager: FileManager = .default) -> [String] {
        var lines: [String] = []
        for folder in ["Desktop", "Applications"] {
            let dir = home.appendingPathComponent(folder, isDirectory: true)
            for entry in (try? fileManager.contentsOfDirectory(atPath: dir.path)) ?? [] where entry.hasSuffix(".app") {
                let app = dir.appendingPathComponent(entry, isDirectory: true)
                let script = app.appendingPathComponent("Contents/MacOS/\(scriptName)")
                guard let text = try? String(contentsOf: script, encoding: .utf8),
                      text.contains("# autogenerated file"), let id = appID(runScript: text), games.contains(id)
                else { continue }
                var changed: [String] = []
                let wanted = runScript(appID: id, steamLauncher: steamLauncher)
                if text != wanted, (try? Data(wanted.utf8).write(to: script, options: .atomic)) != nil {
                    try? fileManager.setAttributes([.posixPermissions: 0o755], ofItemAtPath: script.path)
                    changed.append("starts Steam (Silo)")
                }
                let icon = app.appendingPathComponent("Contents/Resources/\(iconName)")
                if let gameIcon = gameAppIcon(id: id, in: gameAppsDir, fileManager: fileManager),
                   let data = try? Data(contentsOf: gameIcon), (try? Data(contentsOf: icon)) != data,
                   // Written in place, not swapped: the Finder then goes from Steam's icon straight to the game's,
                   // without the blank tile a replaced file left for a moment (user, 2026-11-18).
                   (try? data.write(to: icon)) != nil {
                    changed.append("game icon")
                }
                guard !changed.isEmpty else { continue }
                // A new modification date makes the Finder and the Dock read the icon again.
                try? fileManager.setAttributes([.modificationDate: Date()], ofItemAtPath: app.path)
                lines.append("shortcut \(folder)/\(entry): " + changed.joined(separator: ", "))
            }
        }
        return lines
    }

    /// The `.icns` of the game app Silo made for `id` (`GameApps/<id>/<name>.app`), if any.
    static func gameAppIcon(id: Int, in gameAppsDir: URL, fileManager: FileManager) -> URL? {
        let dir = gameAppsDir.appendingPathComponent(String(id), isDirectory: true)
        let app = ((try? fileManager.contentsOfDirectory(atPath: dir.path)) ?? []).first { $0.hasSuffix(".app") }
        guard let app else { return nil }
        let icon = dir.appendingPathComponent("\(app)/Contents/Resources/\(GameHostBundle.iconName).icns")
        return fileManager.fileExists(atPath: icon.path) ? icon : nil
    }
}
